// Versioning proposal files: a config-directory .gitignore covering
// unversioned artifact paths that live inside the config directory, and a
// root-relative proposal document for paths outside it. The project root
// .gitignore is NEVER modified by TaskSystem; no Git command is run.
import { err } from './errors.mjs';
import { VERSIONING_KEYS } from './config.mjs';
import { loadOnboardingDefaults } from './policy.mjs';
import { portableKey } from './paths.mjs';

const REPORT_CATEGORIES = ['plans', 'tasks', 'reports', 'research',
  'decisions', 'memory', 'state'];

// Literal path segments in gitignore patterns need escaping for glob
// metacharacters that paths.mjs does not already forbid: [ ] # !.
function escapeLiteral(seg) {
  return seg.replace(/[[\]#!\\]/g, (c) => '\\' + c);
}

function isInsideConfigDir(configDir, rel) {
  return configDir !== '.'
    && portableKey(rel).startsWith(portableKey(configDir) + '/');
}

// Patterns for one category at a given anchored base (no trailing slash).
// reviews has no own path: it is <reports>/<reviewSubdir>. Shared vs local
// mixes follow the settled spec exactly.
function categoryPatterns(key, paths, versioning, base) {
  if (key !== 'reports') {
    return versioning[key] ? [] : [`${escapeLiteral(base)}/`];
  }
  const rev = `${escapeLiteral(base)}/${loadOnboardingDefaults().reviewSubdirectory}`;
  const r = versioning.reports;
  const v = versioning.reviews;
  if (!r && !v) return [`${escapeLiteral(base)}/`];
  if (!r && v) return [`${escapeLiteral(base)}/*`, `!${rev}/`];
  if (r && !v) return [`${rev}/`];
  return [];
}

// Returns [{rel, content}] for <configDir>/.gitignore (skipped entirely when
// configDir is the project root) and integrations/gitignore-proposal.txt.
export function buildVersioningFiles({ configDir, paths, versioning }) {
  for (const k of VERSIONING_KEYS) {
    if (typeof versioning[k] !== 'boolean') {
      throw err('INVALID_VALUE', `versioning.${k} must be boolean`);
    }
  }
  const subOf = (rel) => rel.slice(configDir.length + 1);
  const ignoreLines = [];
  const proposalLines = [];

  for (const key of REPORT_CATEGORIES) {
    const rel = paths[key];
    if (isInsideConfigDir(configDir, rel)) {
      ignoreLines.push(...categoryPatterns(key, paths, versioning, `/${subOf(rel)}`));
    } else {
      proposalLines.push(...categoryPatterns(key, paths, versioning, `/${rel}`));
    }
  }

  const files = [];
  if (configDir !== '.') {
    files.push({
      rel: `${configDir}/.gitignore`,
      content: [
        '# Generated by TaskSystem init: artifact categories opted OUT of',
        '# versioning. A nested .gitignore cannot undo a parent ignore or',
        '# untrack files that are already tracked; owner review required.',
        '# TaskSystem never modifies the project root .gitignore.',
        '',
        ...ignoreLines,
        '',
      ].join('\n'),
    });
  }
  files.push({
    rel: `${configDir === '.' ? '' : configDir + '/'}integrations/gitignore-proposal.txt`,
    content: [
      '# TaskSystem versioning proposal (review before applying manually)',
      '#',
      '# Patterns below are PROJECT-ROOT relative and cover artifact paths',
      '# that live OUTSIDE the config directory, so no nested .gitignore',
      '# generated by TaskSystem can cover them.',
      '#',
      '# Caveats:',
      '# - TaskSystem never edits the project root .gitignore automatically.',
      '# - A nested .gitignore cannot undo a parent ignore rule.',
      '# - Files already tracked by Git need owner review (e.g. git rm',
      '#   --cached); ignore rules alone do not untrack them.',
      '# - No Git command was executed; this proposal is not validated.',
      '',
      ...(proposalLines.length > 0
        ? proposalLines
        : ['# (no outside-workspace unversioned artifact paths)']),
      '',
    ].join('\n'),
  });
  return files;
}
